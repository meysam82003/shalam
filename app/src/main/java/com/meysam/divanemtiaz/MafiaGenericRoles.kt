    /** Options shown at setup for a data-defined role (uses, day uses, armour). */
    fun options(role: MafiaRole): List<MafiaOptionDef> {
        val d = MafiaRoleRegistry.def(role) ?: return emptyList()
        val list = ArrayList<MafiaOptionDef>()
        if (role == MafiaRole.CITIZEN || role == MafiaRole.MAFIA) return list
        val ability = d.ability ?: MafiaAbility.NONE
        if (ability != MafiaAbility.NONE) list += MafiaOptionDef(USES, counts, if ((d.uses ?: 0) <= 0) "∞" else d.uses.toString())
        if ((d.dayAbility ?: MafiaDayAbility.NONE) != MafiaDayAbility.NONE) list += MafiaOptionDef(DAY_USES, counts, if ((d.dayUses ?: 0) <= 0) "∞" else d.dayUses.toString())
        list += MafiaOptionDef(ARMOR, listOf("0", "1", "2", "3"), (d.armor ?: 0).toString())
        return list
    }

