<?php
/** Divan Emtiaz server — installation helpers (requirements, config file, first admin). */

declare(strict_types=1);

if (!defined('DIVAN')) { http_response_code(403); exit; }

final class Installer
{
    /** @return array<int, array{0:string,1:bool,2:string,3:bool}> [label, ok, detail, required] */
    public static function checks(): array
    {
        $root = App::$root;
        $https = (!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off') || (($_SERVER['HTTP_X_FORWARDED_PROTO'] ?? '') === 'https');
        $c = [];
        $c[] = ['نسخهٔ PHP (۷٫۴ یا بالاتر)', PHP_VERSION_ID >= 70400, PHP_VERSION, true];
        foreach (['pdo_mysql' => 'اتصال MySQL (pdo_mysql)', 'openssl' => 'رمزنگاری (openssl)', 'json' => 'JSON', 'mbstring' => 'متن چندبایتی (mbstring)', 'curl' => 'درخواست به بازار و مایکت (curl)', 'fileinfo' => 'تشخیص نوع فایل (fileinfo)', 'zlib' => 'فشرده‌سازی پشتیبان (zlib)'] as $ext => $label) {
            $c[] = [$label, extension_loaded($ext), extension_loaded($ext) ? 'فعال' : 'غیرفعال', true];
        }
        $c[] = ['کتابخانهٔ تصویر (gd)', extension_loaded('gd'), extension_loaded('gd') ? 'فعال' : 'اختیاری', false];
        foreach (['storage', 'storage/keys', 'storage/backups', 'storage/logs', 'media'] as $d) {
            // Missing folders (some hosts drop empty folders from a ZIP) are created with a blank index page.
            if (!is_dir("$root/$d")) @mkdir("$root/$d", 0755, true);
            if (is_dir("$root/$d") && !is_file("$root/$d/index.html")) @file_put_contents("$root/$d/index.html", '<!doctype html><title></title>');
            $ok = is_dir("$root/$d") && is_writable("$root/$d");
            $c[] = ["پوشهٔ قابل نوشتن: $d", $ok, $ok ? 'قابل نوشتن' : 'مجوز نوشتن ندارد (۷۵۵)', true];
        }
        $c[] = ['اتصال امن HTTPS', $https, $https ? 'فعال' : 'سایت را با https باز کنید', true];
        $ok = false;
        if (function_exists('openssl_pkey_new')) { $k = @openssl_pkey_new(['private_key_bits' => 2048, 'private_key_type' => OPENSSL_KEYTYPE_RSA]); $ok = $k !== false; }
        $c[] = ['ساخت کلید RSA', $ok, $ok ? 'ممکن' : 'openssl تنظیم نیست', true];
        $c[] = ['محافظت پوشه‌ها (.htaccess)', is_file("$root/storage/.htaccess") && is_file("$root/app/.htaccess"), 'فایل‌های .htaccess', true];
        return $c;
    }

    public static function ready(): bool
    {
        foreach (self::checks() as [$l, $ok, $d, $req]) if ($req && !$ok) return false;
        return true;
    }

    public static function writeConfig(array $cfg): void
    {
        $php = "<?php\n// Divan Emtiaz — generated by the installer. Keep this file private.\nreturn " . var_export($cfg, true) . ";\n";
        $file = App::configFile();
        if (file_put_contents($file . '.tmp', $php) === false) throw new RuntimeException('cannot write config');
        rename($file . '.tmp', $file);
        @chmod($file, 0600);
        App::$config = $cfg;
        if (function_exists('opcache_invalidate')) @opcache_invalidate($file, true);
    }

    public static function lock(): void
    {
        file_put_contents(App::$root . '/storage/install.lock', gmdate('c'));
    }

    public static function validateAdminPassword(string $p): ?string
    {
        if (strlen($p) < 12) return 'رمز مدیر باید دست‌کم ۱۲ نویسه باشد.';
        if (!preg_match('/[a-z]/', $p) || !preg_match('/[A-Z]/', $p) || !preg_match('/[0-9]/', $p)) return 'رمز مدیر باید حرف کوچک، حرف بزرگ انگلیسی و عدد داشته باشد.';
        return null;
    }
}
