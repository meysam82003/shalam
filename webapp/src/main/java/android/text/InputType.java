package android.text;

public interface InputType {
    int TYPE_MASK_CLASS = 0x0000000f, TYPE_MASK_VARIATION = 0x00000ff0, TYPE_MASK_FLAGS = 0x00fff000;
    int TYPE_NULL = 0;
    int TYPE_CLASS_TEXT = 0x00000001;
    int TYPE_TEXT_FLAG_CAP_CHARACTERS = 0x00001000, TYPE_TEXT_FLAG_CAP_WORDS = 0x00002000, TYPE_TEXT_FLAG_CAP_SENTENCES = 0x00004000,
        TYPE_TEXT_FLAG_AUTO_CORRECT = 0x00008000, TYPE_TEXT_FLAG_AUTO_COMPLETE = 0x00010000, TYPE_TEXT_FLAG_MULTI_LINE = 0x00020000,
        TYPE_TEXT_FLAG_IME_MULTI_LINE = 0x00040000, TYPE_TEXT_FLAG_NO_SUGGESTIONS = 0x00080000;
    int TYPE_TEXT_VARIATION_NORMAL = 0, TYPE_TEXT_VARIATION_URI = 0x10, TYPE_TEXT_VARIATION_EMAIL_ADDRESS = 0x20, TYPE_TEXT_VARIATION_PERSON_NAME = 0x60,
        TYPE_TEXT_VARIATION_PASSWORD = 0x80, TYPE_TEXT_VARIATION_VISIBLE_PASSWORD = 0x90, TYPE_TEXT_VARIATION_WEB_PASSWORD = 0xe0;
    int TYPE_CLASS_NUMBER = 0x00000002;
    int TYPE_NUMBER_FLAG_SIGNED = 0x00001000, TYPE_NUMBER_FLAG_DECIMAL = 0x00002000, TYPE_NUMBER_VARIATION_PASSWORD = 0x10;
    int TYPE_CLASS_PHONE = 0x00000003;
    int TYPE_CLASS_DATETIME = 0x00000004;
}
